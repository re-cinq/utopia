/// Generates the push key for an api source.
pub(crate) fn new_ingest_token() -> String {
    format!("utp_{}{}", Uuid::new_v4().simple(), Uuid::new_v4().simple())
}

/// Whether the pushed key is correct. **Constant-time comparison.**
///
/// This is not guarding against timing attacks: on this path it cannot land a hit. The key is a 244-bit random string generated by the server
/// (`new_ingest_token`, two v4 UUIDs concatenated), and the comparison happens after a database round trip,
/// where network and query jitter in milliseconds swamps any nanosecond difference. What actually protects this key is its entropy.
///
/// It is written this way so **the reader does not have to re-derive the paragraph above**: the other two token paths in the repo
/// do no plaintext comparison (personal tokens store a sha256 and look up by hash, sessions verify a JWT signature), so this is the only
/// place plaintext is compared with plaintext, and it should look like it was considered.
///
/// A length mismatch returns immediately: `ct_eq` is only meaningful for equal-length slices. The key length is fixed (`utp_` + 64
/// hex characters) and is not part of the secret, so short-circuiting here leaks nothing.
fn push_key_matches(stored: Option<&str>, offered: &str) -> bool {
    let Some(stored) = stored else {
        return false;
    };
    if stored.len() != offered.len() {
        return false;
    }
    use subtle::ConstantTimeEq;
    stored.as_bytes().ct_eq(offered.as_bytes()).into()
}

/// Fetch a source and confirm it belongs to the KB on the path.
///
/// `require_kb` only checks the person's permission on the KB; the source id is a separate dimension: without this check, an Editor of KB A
/// holding the id of a source in KB B could sync, clean up, or delete it. Not belonging is treated as nonexistent (404),
/// consistent with what `get_token` has always done
pub(crate) async fn source_in_kb(
    state: &AppState,
    kb_id: Uuid,
    source_id: Uuid,
) -> ApiResult<utopia_core::models::Source> {
    let source = utopia_store::sources::get(&state.pool, source_id).await?;
    if source.kb_id != kb_id {
        return Err(utopia_core::AppError::NotFound.into());
    }
    Ok(source)
}

/// Edit, delete, clean up missing entries, or re-extract a source. Tokens cover push-type sources only, on the same line as creating a source (0014 decision 6):
/// if a `url` address can be changed, a leaked token could make the server knock on any address. Sessions still govern all sources
async fn source_to_manage(
    state: &AppState,
    caller: &SessionOrToken,
    kb_id: Uuid,
    source_id: Uuid,
) -> ApiResult<utopia_core::models::Source> {
    caller.require_write(Some(kb_id))?;
    require_kb(state, &caller.user, kb_id, Role::Editor).await?;
    let source = source_in_kb(state, kb_id, source_id).await?;
    if caller.pat.is_some() && !is_push_kind(&source.kind) {
        return Err(utopia_core::AppError::CodedForbidden {
            code: "token_source_kind",
            message: "A token manages only statements or api sources; other kinds take a session"
                .into(),
        }
        .into());
    }
    Ok(source)
}

