pub async fn delete(
    State(state): State<AppState>,
    caller: SessionOrToken,
    Path((kb_id, source_id)): Path<(Uuid, Uuid)>,
) -> ApiResult<Json<serde_json::Value>> {
    // Memory source is permanent: the memory space does not evaporate just because the source is tidied (the memory document itself can be deleted in Library)
    let source = source_to_manage(&state, &caller, kb_id, source_id).await?;
    if source.kind == utopia_store::memory::MEMORY_SOURCE_KIND {
        return Err(utopia_core::AppError::invalid(
            "memory_source_permanent",
            "The Memory source is permanent.",
        )
        .into());
    }
    utopia_store::sources::delete(&state.pool, source_id).await?;
    state.emit_source(kb_id);
    let _ = utopia_store::audit::record(
        &state.pool,
        Some(kb_id),
        caller.user.id,
        "source.deleted",
        "source",
        Some(source_id),
        utopia_store::audit::via_token(json!({}), caller.token_id()),
    )
    .await;
    Ok(Json(json!({ "ok": true })))
}

