/// Write tokens can also create sources (0014 decision 6): setting up a `statements` or `api` source for a mirror repo should not require a person
/// to click them one by one.
///
/// Tokens create push-type sources only (`statements`/`api`; the server pulls nothing for them): `url`/`rss`/`custom`
/// are pulled on a schedule as soon as they are created (`custom` also carries stored credentials), and a leaked CI token must not let the server
/// knock on arbitrary addresses on a timer. Sessions can still create anything
pub async fn create(
    State(state): State<AppState>,
    caller: SessionOrToken,
    Path(kb_id): Path<Uuid>,
    Json(body): Json<CreateBody>,
) -> ApiResult<Json<serde_json::Value>> {
    caller.require_write(Some(kb_id))?;
    if caller.pat.is_some() && !is_push_kind(&body.kind) {
        return Err(utopia_core::AppError::CodedForbidden {
            code: "token_source_kind",
            message: "A token creates only statements or api sources; other kinds take a session"
                .into(),
        }
        .into());
    }
    let token_id = caller.token_id();
    let user = caller.user;
    require_kb(&state, &user, kb_id, Role::Editor).await?;
    validate_rss_config(&body.kind, &body.config)?;
    let drive = config_is_drive_owned(&body.kind);
    // A deployment without an OAuth client cannot reach Google, and a source created there would only ever fail (0074 decision 2)
    if drive && crate::google_drive::oauth_config().is_none() {
        return Err(utopia_core::AppError::invalid(
            "google_drive_not_configured",
            "Google Drive is not configured on this server",
        )
        .into());
    }
    let config = if drive { json!({}) } else { body.config };
    let source = utopia_store::sources::create(
        &state.pool,
        kb_id,
        &body.kind,
        &body.name,
        &config,
        body.icon.as_deref(),
        body.sync_interval_minutes,
        body.sync_cron.as_deref(),
    )
    .await?;
    // A pull-type source is synced once right after creation (if configured it produces output, with no need to wait for the next schedule tick)
    if matches!(source.kind.as_str(), "url" | "rss" | "custom") {
        utopia_store::sources::enqueue_sync(&state.pool, source.id).await?;
    }
    // api source: generate a dedicated push key (viewable any time afterwards via get_token)
    let mut ingest_token: Option<String> = None;
    if is_push_kind(&source.kind) {
        let token = new_ingest_token();
        utopia_store::sources::set_ingest_token(&state.pool, source.id, &token).await?;
        ingest_token = Some(token);
    }
    state.emit_source(kb_id);
    let _ = utopia_store::audit::record(
        &state.pool,
        Some(kb_id),
        user.id,
        "source.created",
        "source",
        Some(source.id),
        utopia_store::audit::via_token(
            json!({ "kind": source.kind, "name": source.name }),
            token_id,
        ),
    )
    .await;
    Ok(Json(
        json!({ "source": mask_secrets(source), "ingest_token": ingest_token }),
    ))
}

/// View the push key (Editor; list responses never carry it, viewing goes through here).
///
/// The token needs write: the key can push into the KB, so a read token that obtained it would be bypassing its own scope
pub async fn get_token(
    State(state): State<AppState>,
    caller: SessionOrToken,
    Path((kb_id, source_id)): Path<(Uuid, Uuid)>,
) -> ApiResult<Json<serde_json::Value>> {
    caller.require_write(Some(kb_id))?;
    require_kb(&state, &caller.user, kb_id, Role::Editor).await?;
    let source = source_in_kb(&state, kb_id, source_id).await?;
    if !is_push_kind(&source.kind) {
        return Err(utopia_core::AppError::NotFound.into());
    }
    Ok(Json(json!({ "ingest_token": source.ingest_token })))
}

/// Rotate the push key: the old key stops working immediately.
pub async fn rotate_token(
    State(state): State<AppState>,
    AuthUser(user): AuthUser,
    Path((kb_id, source_id)): Path<(Uuid, Uuid)>,
) -> ApiResult<Json<serde_json::Value>> {
    require_kb(&state, &user, kb_id, Role::Editor).await?;
    let source = source_in_kb(&state, kb_id, source_id).await?;
    if !is_push_kind(&source.kind) {
        return Err(utopia_core::AppError::NotFound.into());
    }
    let token = new_ingest_token();
    utopia_store::sources::set_ingest_token(&state.pool, source_id, &token).await?;
    Ok(Json(json!({ "ingest_token": token })))
}

/// Strip credentials before responding (in only, never out; keys are listed in `SOURCE_SECRET_KEYS`).
fn mask_secrets(source: utopia_core::models::Source) -> utopia_core::models::Source {
    source.without_secrets()
}

fn validate_rss_config(kind: &str, config: &serde_json::Value) -> utopia_core::AppResult<()> {
    if kind == "rss" {
        utopia_store::sources::rss_content_mode(config)?;
    }
    Ok(())
}

/// A Google Drive source's config is written only by its own three routes: connect, pick folder, disconnect (0074).
/// If the generic create and update could also write it, any editor could bypass "only the person who connected can pick the folder"
fn config_is_drive_owned(kind: &str) -> bool {
    SourceKind::parse(kind) == Some(SourceKind::GoogleDrive)
}

/// Credential merge rule on update, applied to each key in `SOURCE_SECRET_KEYS`: if the new config has **no** such key
/// or the value is an empty string, keep the value in the DB (a blank form field means "leave it alone"); an explicit `null` deletes it;
/// anything else takes the new value. Responses never echo them back, so clients have no way to send the old value back unchanged; the rule has to live here
fn keep_secrets(next: &mut serde_json::Value, existing: &serde_json::Value) {
    let Some(obj) = next.as_object_mut() else {
        return;
    };
    for key in SOURCE_SECRET_KEYS {
        let keep = match obj.get(*key) {
            None => true,
            Some(serde_json::Value::Null) => {
                obj.remove(*key);
                false
            }
            Some(v) => v.as_str().is_some_and(|s| s.trim().is_empty()),
        };
        if keep {
            obj.remove(*key);
            if let Some(prev) = existing.get(*key) {
                obj.insert((*key).to_string(), prev.clone());
            }
        }
    }
}

#[derive(Deserialize)]
pub struct UpdateBody {
    pub name: Option<String>,
    pub config: Option<serde_json::Value>,
    pub icon: Option<String>,
    /// If a schedule field is present, it overrides the whole schedule (interval and cron are mutually exclusive; both null = schedule off)
    #[serde(default)]
    pub schedule: Option<ScheduleBody>,
    /// Absent = unchanged; `null` = turn off decay; object = turn on (RC-003)
    #[serde(default, deserialize_with = "present_even_when_null")]
    pub decay: Option<Option<utopia_store::decay::DecaySettings>>,
}

/// Distinguishes "this field was not written" from "written as null": the former is an outer `None`, the latter `Some(None)`.
fn present_even_when_null<'de, D, T>(deserializer: D) -> Result<Option<Option<T>>, D::Error>
where
    D: serde::Deserializer<'de>,
    T: Deserialize<'de>,
{
    Option::<T>::deserialize(deserializer).map(Some)
}

#[derive(Deserialize)]
pub struct ScheduleBody {
    #[serde(default)]
    pub sync_interval_minutes: Option<i32>,
    #[serde(default)]
    pub sync_cron: Option<String>,
}

pub async fn update(
    State(state): State<AppState>,
    caller: SessionOrToken,
    Path((kb_id, source_id)): Path<(Uuid, Uuid)>,
    Json(body): Json<UpdateBody>,
) -> ApiResult<Json<serde_json::Value>> {
    let existing = source_to_manage(&state, &caller, kb_id, source_id).await?;
    // Credentials go in and never come out: responses never echo them, a blank form field or one not sent = keep the value in the DB
    let mut config = body
        .config
        .filter(|_| !config_is_drive_owned(&existing.kind));
    if let Some(cfg) = config.as_mut() {
        keep_secrets(cfg, &existing.config);
    }
    if let Some(cfg) = config.as_ref() {
        validate_rss_config(&existing.kind, cfg)?;
    }
    let source = utopia_store::sources::update(
        &state.pool,
        source_id,
        body.name.as_deref(),
        config.as_ref(),
        body.icon.as_deref(),
        body.schedule
            .map(|s| (s.sync_interval_minutes, s.sync_cron)),
        body.decay.as_ref().map(Option::as_ref),
    )
    .await?;
    state.emit_source(kb_id);
    // Audit does not record credentials: config only records whether it changed
    let _ = utopia_store::audit::record(
        &state.pool,
        Some(kb_id),
        caller.user.id,
        "source.updated",
        "source",
        Some(source_id),
        utopia_store::audit::via_token(
            json!({
                "name": body.name,
                "config_changed": config.is_some(),
                "decay_changed": body.decay.is_some()
            }),
            caller.token_id(),
        ),
    )
    .await;
    Ok(Json(json!({ "source": mask_secrets(source) })))
}

/// Bulk delete all documents under this source that are "not in the source" (flagged by url reconciliation / custom tombstones).
pub async fn cleanup_missing(
    State(state): State<AppState>,
    caller: SessionOrToken,
    Path((kb_id, source_id)): Path<(Uuid, Uuid)>,
) -> ApiResult<Json<serde_json::Value>> {
    source_to_manage(&state, &caller, kb_id, source_id).await?;
    let ids = utopia_store::documents::list_missing(&state.pool, source_id).await?;
    for id in &ids {
        utopia_store::documents::delete(&state.pool, kb_id, *id, Some(caller.user.id)).await?;
        let search = state.search.clone();
        let did = id.to_string();
        tokio::task::spawn_blocking(move || search.delete_document(&did))
            .await
            .map_err(|e| utopia_core::AppError::Other(e.into()))?
            .map_err(utopia_core::AppError::Other)?;
    }
    // Same wrap-up as single deletion: the premise is gone, so the derived state follows at once, rather than being left to the next scheduled derivation (#875).
    // A batch is pushed only once
    if !ids.is_empty() {
        super::documents_routes::settle_derivations(&state, kb_id).await?;
    }
    state.emit_source(kb_id);
    Ok(Json(json!({ "deleted": ids.len() })))
}

