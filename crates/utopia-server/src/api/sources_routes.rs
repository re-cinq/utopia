#[derive(Deserialize)]
pub struct IngestBody {
    /// When a tombstone carries an external_id, the filename is not needed (identity is external_id); it is accepted even if missing,
    /// otherwise it is still required, and an empty string is blocked by the validation below
    #[serde(default)]
    pub filename: String,
    /// A tombstone push (`deleted: true`) may omit content: the guide has always said so, but the field
    /// used to be required, so a missing one was rejected at deserialization. Otherwise it is still required: an empty string is blocked by
    /// the validation below
    #[serde(default)]
    pub content: String,
    #[serde(default)]
    pub doc_time: Option<DateTime<Utc>>,
    /// The caller's logical document ID: pushing the same ID again = update the same document (in-place replacement + version record).
    /// If not given, the filename is the identity.
    #[serde(default)]
    pub external_id: Option<String>,
    /// Tombstone: true = mark "not in the source" by identity (does not delete; supported only for api source pushes).
    /// content may be omitted in this case; a normal push with the same identity again clears the mark.
    #[serde(default)]
    pub deleted: bool,
}

/// Receipt for a push: the action, plus, on a duplicate, the document that already holds this content
fn action_reply(action: crate::ingest_sources::IngestAction) -> serde_json::Value {
    match action {
        crate::ingest_sources::IngestAction::Duplicate(id) => {
            json!({ "action": action_str(action), "duplicate_of": id })
        }
        _ => json!({ "action": action_str(action) }),
    }
}

fn action_str(action: crate::ingest_sources::IngestAction) -> &'static str {
    match action {
        crate::ingest_sources::IngestAction::Created => "created",
        crate::ingest_sources::IngestAction::Updated => "updated",
        crate::ingest_sources::IngestAction::Moved => "moved",
        crate::ingest_sources::IngestAction::Unchanged => "unchanged",
        crate::ingest_sources::IngestAction::Tombstoned => "marked_missing",
        crate::ingest_sources::IngestAction::Duplicate(_) => "duplicate",
    }
}

/// KB-level text push (session auth): ordinary upload semantics; lands in Uploads, with no identity tracking.
/// When "same ID again = update" semantics are needed, create an api source and push with its key.
pub async fn ingest(
    State(state): State<AppState>,
    AuthUser(user): AuthUser,
    Path(kb_id): Path<Uuid>,
    Json(body): Json<IngestBody>,
) -> ApiResult<Json<serde_json::Value>> {
    require_kb(&state, &user, kb_id, Role::Editor).await?;
    if body.deleted {
        return Err(utopia_core::AppError::Validation(
            "tombstones need identity tracking — push to an api source instead".into(),
        )
        .into());
    }
    if body.filename.trim().is_empty() || body.content.trim().is_empty() {
        return Err(
            utopia_core::AppError::Validation("filename and content are required".into()).into(),
        );
    }
    let action = crate::ingest_sources::ingest_upload(
        &state,
        kb_id,
        body.filename.trim(),
        "text/plain",
        body.content.as_bytes(),
        body.doc_time,
    )
    .await
    .map_err(utopia_core::AppError::Other)?;
    Ok(Json(action_reply(action)))
}

/// Two kinds of push failure. **A bad request from the caller** and **something we failed to handle** must be kept apart: the former is recorded in the
/// run for integration debugging, but does not count as a sync failure of the source: the source is fine, that one request was malformed;
/// only the latter should mark the source as failed and go to the alert center. Before, both went through `finish_sync(error)`, so
/// one malformed entry made the bell say "source sync failed, no new content came in"
enum PushError {
    /// 4xx: malformed payload (JSON parse, missing fields)
    Rejected(String),
    /// Ingestion itself failed
    Failed(String),
}

impl PushError {
    fn message(&self) -> &str {
        match self {
            PushError::Rejected(m) | PushError::Failed(m) => m,
        }
    }
}

/// Push handling after auth: parse + validate + ingest / tombstone. Errors are always returned as text (recorded in the run).
async fn handle_push(
    state: &AppState,
    source: &utopia_core::models::Source,
    bytes: &[u8],
) -> Result<crate::ingest_sources::IngestAction, PushError> {
    let body: IngestBody = serde_json::from_slice(bytes)
        .map_err(|e| PushError::Rejected(format!("Invalid JSON payload: {e}")))?;
    let declared = body
        .external_id
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty());
    let identity = declared.unwrap_or_else(|| body.filename.trim()).to_string();
    if identity.is_empty() {
        return Err(PushError::Rejected(
            "external_id or filename is required".into(),
        ));
    }
    let key = pushed_key(source, &identity);

    // Tombstone: mark "not in the source" (same path as custom's deleted[]); content may be omitted
    if body.deleted {
        utopia_store::documents::mark_missing_keys(&state.pool, source.id, &[key])
            .await
            .map_err(|e| PushError::Failed(e.to_string()))?;
        return Ok(crate::ingest_sources::IngestAction::Tombstoned);
    }

    if body.filename.trim().is_empty() || body.content.trim().is_empty() {
        return Err(PushError::Rejected(
            "filename and content are required".into(),
        ));
    }
    // If an external_id identity is given, it is that identity: no "same content = move", and it does not turn another ID's document into this one
    let action = crate::ingest_sources::ingest_item_with_outcome(
        state,
        source.kb_id,
        source.id,
        &key,
        if declared.is_some() {
            crate::ingest_sources::Identity::Declared
        } else {
            crate::ingest_sources::Identity::Path
        },
        body.filename.trim(),
        "text/plain",
        body.content.as_bytes(),
        body.doc_time,
    )
    .await
    .map_err(|e| PushError::Failed(e.to_string()))?
    .action;
    // Regained: an identity previously marked by a tombstone that is pushed normally again clears the missing mark; a duplicate push writes nothing and does not clear it
    if !matches!(action, crate::ingest_sources::IngestAction::Duplicate(_)) {
        utopia_store::documents::clear_missing_keys(&state.pool, source.id, &[key])
            .await
            .map_err(|e| PushError::Failed(e.to_string()))?;
    }
    Ok(action)
}

/// api source push (authenticated by a source-specific key, no session): three identity semantics:
/// new external_id -> create; same ID same content -> no-op; same ID new content -> update in place + version record.
/// Every push after auth records one run (including malformed ones; integration debugging depends on it);
/// unauthenticated requests write no record at all (so anonymous traffic cannot create a path to the DB).
pub async fn push(
    State(state): State<AppState>,
    Path(source_id): Path<Uuid>,
    headers: HeaderMap,
    bytes: axum::body::Bytes,
) -> ApiResult<Json<serde_json::Value>> {
    let source = utopia_store::sources::get(&state.pool, source_id).await?;
    if source.kind != "api" {
        return Err(utopia_core::AppError::NotFound.into());
    }
    // Bearer key check
    let token = headers
        .get("authorization")
        .and_then(|v| v.to_str().ok())
        .and_then(|v| v.strip_prefix("Bearer "))
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .ok_or(utopia_core::AppError::Unauthorized)?;
    if !push_key_matches(source.ingest_token.as_deref(), token) {
        return Err(utopia_core::AppError::Unauthorized.into());
    }

    let run = utopia_store::sources::start_run(&state.pool, source.id).await?;
    match handle_push(&state, &source, &bytes).await {
        Ok(action) => {
            let (created, updated) = match action {
                crate::ingest_sources::IngestAction::Created => (1, 0),
                crate::ingest_sources::IngestAction::Updated
                | crate::ingest_sources::IngestAction::Moved => (0, 1),
                crate::ingest_sources::IngestAction::Unchanged
                | crate::ingest_sources::IngestAction::Tombstoned
                | crate::ingest_sources::IngestAction::Duplicate(_) => (0, 0),
            };
            utopia_store::sources::finish_run(&state.pool, run, source.id, None, created, updated)
                .await?;
            // The source row reflects the "last push" at once, so the action bar and the sidebar status dot are immediately usable
            utopia_store::sources::finish_sync(&state.pool, source.id, None, created).await?;
            state.emit_source(source.kb_id);
            Ok(Json(action_reply(action)))
        }
        Err(err) => {
            let msg = err.message().to_string();
            utopia_store::sources::finish_run(&state.pool, run, source.id, Some(&msg), 0, 0)
                .await?;
            // Only count it as a source failure when we failed to handle it; a bad request from the caller is enough to leave in the run history
            if let PushError::Failed(_) = err {
                utopia_store::sources::finish_sync(&state.pool, source.id, Some(&msg), 0).await?;
            }
            state.emit_source(source.kb_id);
            Err(utopia_core::AppError::Validation(msg).into())
        }
    }
}

/// Push statements (0054): the request body is the open extraction contract (`e` / `s` / `n`), plus the envelope layer that `api` push adds.
///
/// Same key, same identity semantics (`statements:{external_id}`), same run record as `push`;
/// only two things differ, and both are fixed at the door: **the payload becomes the document as is, as one block**, parsed against the contract at extraction without asking
/// the model; **any key outside the envelope and contract is refused**: the contract has no slots for attributes, classes or predicates, so
/// a caller that writes `predicate` should get a 422 here, rather than a type fact it thought it wrote not being found in the graph.
pub async fn push_statements(
    State(state): State<AppState>,
    Path(source_id): Path<Uuid>,
    headers: HeaderMap,
    bytes: axum::body::Bytes,
) -> ApiResult<Json<serde_json::Value>> {
    let source = utopia_store::sources::get(&state.pool, source_id).await?;
    if source.kind != "statements" {
        return Err(utopia_core::AppError::NotFound.into());
    }
    let token = headers
        .get("authorization")
        .and_then(|v| v.to_str().ok())
        .and_then(|v| v.strip_prefix("Bearer "))
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .ok_or(utopia_core::AppError::Unauthorized)?;
    if !push_key_matches(source.ingest_token.as_deref(), token) {
        return Err(utopia_core::AppError::Unauthorized.into());
    }

    let run = utopia_store::sources::start_run(&state.pool, source.id).await?;
    match handle_statements_push(&state, &source, &bytes).await {
        Ok(action) => {
            let (created, updated) = match action {
                crate::ingest_sources::IngestAction::Created => (1, 0),
                crate::ingest_sources::IngestAction::Updated
                | crate::ingest_sources::IngestAction::Moved => (0, 1),
                crate::ingest_sources::IngestAction::Unchanged
                | crate::ingest_sources::IngestAction::Tombstoned
                | crate::ingest_sources::IngestAction::Duplicate(_) => (0, 0),
            };
            utopia_store::sources::finish_run(&state.pool, run, source.id, None, created, updated)
                .await?;
            utopia_store::sources::finish_sync(&state.pool, source.id, None, created).await?;
            state.emit_source(source.kb_id);
            Ok(Json(action_reply(action)))
        }
        Err(err) => {
            let msg = err.message().to_string();
            utopia_store::sources::finish_run(&state.pool, run, source.id, Some(&msg), 0, 0)
                .await?;
            if let PushError::Failed(_) = err {
                utopia_store::sources::finish_sync(&state.pool, source.id, Some(&msg), 0).await?;
            }
            state.emit_source(source.kb_id);
            Err(utopia_core::AppError::Validation(msg).into())
        }
    }
}

/// Maximum bytes and number of statements per push. A first-slice limit, not part of the contract: one block is one payload,
/// these two numbers only keep a payload from growing so large that review cards and the evidence view cannot render it
pub(crate) const STATEMENTS_MAX_BYTES: usize = 64 * 1024;
const STATEMENTS_MAX_ITEMS: usize = 200;
/// Keys allowed in the envelope. Besides the contract's three arrays, only the three that `api` push also has
const STATEMENTS_ENVELOPE: [&str; 6] = ["external_id", "doc_time", "deleted", "e", "s", "n"];

#[derive(serde::Deserialize)]
struct StatementsBody {
    external_id: String,
    #[serde(default)]
    doc_time: Option<DateTime<Utc>>,
    #[serde(default)]
    deleted: bool,
    #[serde(default)]
    e: serde_json::Value,
    #[serde(default)]
    s: serde_json::Value,
    #[serde(default)]
    n: serde_json::Value,
}

/// Validation at the door: whether the shape is right, whether there are keys outside the contract, and whether each statement's citation cell is empty.
/// On passing, the body is re-serialized from the contract into the document text: what is stored is what we wrote, not the bytes the caller sent:
/// identity, date (if any) and `{e, s, n}`, with fixed key order and no extra whitespace; the block is the contract itself
fn validate_statements_payload(raw: &[u8]) -> Result<(StatementsBody, Option<String>), String> {
    if raw.len() > STATEMENTS_MAX_BYTES {
        return Err(format!(
            "payload is {} bytes; the limit is {STATEMENTS_MAX_BYTES}",
            raw.len()
        ));
    }
    let value: serde_json::Value =
        serde_json::from_slice(raw).map_err(|e| format!("Invalid JSON payload: {e}"))?;
    let Some(map) = value.as_object() else {
        return Err("the payload must be a JSON object".into());
    };
    if let Some(extra) = map
        .keys()
        .find(|k| !STATEMENTS_ENVELOPE.contains(&k.as_str()))
    {
        return Err(format!(
            "unknown key {extra:?}: the contract has no slot for it (allowed: external_id, doc_time, deleted, e, s, n)"
        ));
    }
    let body: StatementsBody =
        serde_json::from_value(value).map_err(|e| format!("Invalid payload: {e}"))?;
    if body.external_id.trim().is_empty() {
        return Err("external_id is required".into());
    }
    if body.deleted {
        return Ok((body, None));
    }
    let arrays = [("e", &body.e), ("s", &body.s), ("n", &body.n)];
    for (key, v) in arrays {
        if !v.is_array() {
            return Err(format!("{key} must be an array"));
        }
    }
    let statements = body.s.as_array().expect("checked above");
    if statements.is_empty() {
        return Err("s must hold at least one statement".into());
    }
    if statements.len() > STATEMENTS_MAX_ITEMS {
        return Err(format!(
            "{} statements; the limit is {STATEMENTS_MAX_ITEMS} per push",
            statements.len()
        ));
    }
    for (i, item) in statements.iter().enumerate() {
        let Some(arr) = item.as_array() else {
            return Err(format!("s[{i}] must be an array of eight slots"));
        };
        if arr.len() != 8 {
            return Err(format!(
                "s[{i}] has {} slots; the contract has eight",
                arr.len()
            ));
        }
        if !arr[0].is_null() {
            return Err(format!(
                "s[{i}][0] (quote) must be null: the item is its own evidence"
            ));
        }
        if !arr[5].is_null() && !arr[5].is_object() {
            return Err(format!("s[{i}][5] (qualifiers) must be an object or null"));
        }
    }
    for (i, item) in body.n.as_array().expect("checked above").iter().enumerate() {
        let Some(arr) = item.as_array() else {
            return Err(format!("n[{i}] must be an array"));
        };
        if arr.len() > 2 && !arr[2].is_null() {
            return Err(format!("n[{i}][2] (quote) must be null"));
        }
    }
    // The stored document carries this observation's identity and date, plus the contract's three arrays (#900). The identity is in the body,
    // so two sightings of the same thing would be two documents with different bodies: a content may exist only once in the KB (`documents_kb_sha_idx`),
    // and the file-source "same content at a new path = rename" detection would therefore never touch it. The parser reads only
    // `e` / `s` / `n` and ignores the two extra keys
    // Only the contract can pass parse_open_response: this runs once at the door, so no other answer can appear at extraction time
    let mut stored = serde_json::Map::new();
    stored.insert("external_id".into(), json!(body.external_id.trim()));
    if let Some(at) = body.doc_time {
        stored.insert("doc_time".into(), json!(at));
    }
    stored.insert("e".into(), body.e.clone());
    stored.insert("s".into(), body.s.clone());
    stored.insert("n".into(), body.n.clone());
    let content = serde_json::to_string_pretty(&serde_json::Value::Object(stored))
        .map_err(|e| format!("cannot serialise the contract: {e}"))?;
    let parsed = utopia_extract::open::parse_open_response(&content)
        .map_err(|e| format!("the contract does not parse: {e}"))?;
    if parsed.skipped > 0 {
        return Err(format!(
            "{} item(s) are malformed for the contract (e: [name, kind, named]; s: [null, subject, phrase, object, value, qualifiers, when, ended]; n: [entity, name, null])",
            parsed.skipped
        ));
    }
    if parsed.statements.is_empty() {
        return Err("no statement survived parsing".into());
    }
    // The subject and the thing an alias belongs to must be in `e` (0054 decision 5): anything not found at extraction is silently dropped as UNKNOWN_REF,
    // and the job of the door is to keep the caller from thinking it was written. The folding rule is the same as extraction's `name_key`:
    // only whitespace and case may differ. Objects are not in this list: they become literal values, and statements still go in
    let listed: std::collections::HashSet<String> = parsed
        .entities
        .iter()
        .map(|e| crate::extraction_open::name_key(&e.name))
        .collect();
    for (i, st) in parsed.statements.iter().enumerate() {
        if !listed.contains(&crate::extraction_open::name_key(&st.subject)) {
            return Err(format!(
                "s[{i}][1] (subject) {:?} is not a thing listed in e",
                st.subject
            ));
        }
    }
    for (i, n) in parsed.names.iter().enumerate() {
        if !listed.contains(&crate::extraction_open::name_key(&n.entity)) {
            return Err(format!(
                "n[{i}][0] (entity) {:?} is not a thing listed in e",
                n.entity
            ));
        }
    }
    Ok((body, Some(content)))
}

async fn handle_statements_push(
    state: &AppState,
    source: &utopia_core::models::Source,
    bytes: &[u8],
) -> Result<crate::ingest_sources::IngestAction, PushError> {
    let (body, content) = validate_statements_payload(bytes).map_err(PushError::Rejected)?;
    let identity = body.external_id.trim().to_string();
    let key = pushed_key(source, &identity);
    let Some(content) = content else {
        utopia_store::documents::mark_missing_keys(&state.pool, source.id, &[key])
            .await
            .map_err(|e| PushError::Failed(e.to_string()))?;
        return Ok(crate::ingest_sources::IngestAction::Tombstoned);
    };
    let filename = format!("{identity}.json");
    let action = crate::ingest_sources::ingest_item_with_outcome(
        state,
        source.kb_id,
        source.id,
        &key,
        crate::ingest_sources::Identity::Declared,
        &filename,
        "application/json",
        content.as_bytes(),
        body.doc_time,
    )
    .await
    .map_err(|e| PushError::Failed(e.to_string()))?
    .action;
    if !matches!(action, crate::ingest_sources::IngestAction::Duplicate(_)) {
        utopia_store::documents::clear_missing_keys(&state.pool, source.id, &[key])
            .await
            .map_err(|e| PushError::Failed(e.to_string()))?;
    }
    Ok(action)
}

/// Source-level full re-extraction (incremental semantics): all ready documents under this source go through extraction again.
/// Runs the normal pipeline: entity resolution, fact deduplication, and temporal conflict handling all apply, and all existing human decisions are kept.
pub async fn re_extract(
    State(state): State<AppState>,
    caller: SessionOrToken,
    Path((kb_id, source_id)): Path<(Uuid, Uuid)>,
) -> ApiResult<Json<serde_json::Value>> {
    let source = source_to_manage(&state, &caller, kb_id, source_id).await?;
    // `queue_extraction` itself also filters out documents of this kind, so what comes back here would be "queued 0"
    // the person who clicked should hear why
    if !source.extracts() {
        return Err(utopia_core::AppError::invalid(
            "source_not_extracted",
            "Documents under this source are searched, not extracted",
        )
        .into());
    }
    // The job is created by queue_extraction in the same transaction as the status; here we only push
    let ids =
        utopia_store::documents::queue_extraction(&state.pool, kb_id, Some(source_id)).await?;
    for id in &ids {
        state.emit_document(kb_id, *id);
    }
    let _ = utopia_store::audit::record(
        &state.pool,
        Some(kb_id),
        caller.user.id,
        "source.re_extract",
        "source",
        Some(source_id),
        utopia_store::audit::via_token(
            json!({ "name": source.name, "documents": ids.len() }),
            caller.token_id(),
        ),
    )
    .await;
    Ok(Json(json!({ "queued": ids.len() })))
}

